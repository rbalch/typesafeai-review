# --- write_outputs: atomicity ------------------------------------------------------


def _write_inputs(tmp_path: Path) -> tuple[str, dict]:
    review = _approve_review()
    engine = AskResult(answers={}, requests=1, input_tokens=10, model='jev-latest')
    md = render_markdown(review)
    json_obj = render_json(review, engine, tmp_path, 'develop', [])
    return md, json_obj


def test_write_outputs_writes_both_files(tmp_path: Path) -> None:
    md, json_obj = _write_inputs(tmp_path)
    write_outputs(tmp_path, md, json_obj)
    assert (tmp_path / OUTPUT_MD).read_text() == md
    assert json.loads((tmp_path / OUTPUT_JSON).read_text()) == json_obj
    assert not (tmp_path / f'{OUTPUT_MD}.tmp').exists()
    assert not (tmp_path / f'{OUTPUT_JSON}.tmp').exists()


def test_write_outputs_failure_after_first_replace_leaves_no_files(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    md, json_obj = _write_inputs(tmp_path)

    real_replace = os.replace
    calls = {'n': 0}

    def flaky_replace(src, dst):  # type: ignore[no-untyped-def]
        calls['n'] += 1
        if calls['n'] == 1:
            return real_replace(src, dst)
        raise OSError('disk full')

    monkeypatch.setattr(os, 'replace', flaky_replace)

    with pytest.raises(RenderError) as exc_info:
        write_outputs(tmp_path, md, json_obj)

    assert isinstance(exc_info.value.__cause__, OSError)
    assert not (tmp_path / OUTPUT_MD).exists()
    assert not (tmp_path / OUTPUT_JSON).exists()
    assert not (tmp_path / f'{OUTPUT_MD}.tmp').exists()
    assert not (tmp_path / f'{OUTPUT_JSON}.tmp').exists()
    assert calls['n'] == 2


def test_write_outputs_counts_mismatch_raises_before_any_write(tmp_path: Path) -> None:
    md, json_obj = _write_inputs(tmp_path)
    json_obj['counts'] = {'blocker': 1, 'important': 0, 'minor': 0, 'nit': 0}

    with pytest.raises(RenderError):
        write_outputs(tmp_path, md, json_obj)

    assert not (tmp_path / OUTPUT_MD).exists()
    assert not (tmp_path / OUTPUT_JSON).exists()
    assert not (tmp_path / f'{OUTPUT_MD}.tmp').exists()
    assert not (tmp_path / f'{OUTPUT_JSON}.tmp').exists()
    assert list(tmp_path.iterdir()) == []


def test_write_outputs_cleanup_survives_a_failed_unlink(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Fix round 1, finding 1: a failing `unlink` during cleanup must not escape as
    a raw `OSError`, and must not stop the remaining cleanup targets from being
    attempted -- the original `RenderError` still propagates.
    """
    md, json_obj = _write_inputs(tmp_path)

    real_replace = os.replace
    replace_calls = {'n': 0}

    def flaky_replace(src, dst):  # type: ignore[no-untyped-def]
        replace_calls['n'] += 1
        if replace_calls['n'] == 1:
            return real_replace(src, dst)
        raise OSError('disk full')

    monkeypatch.setattr(os, 'replace', flaky_replace)

    real_unlink = Path.unlink
    unlink_attempts: list[Path] = []

    def flaky_unlink(self: Path, missing_ok: bool = False) -> None:
        unlink_attempts.append(self)
        if len(unlink_attempts) == 1:
            raise OSError('permission denied')
        real_unlink(self, missing_ok=missing_ok)

    monkeypatch.setattr(Path, 'unlink', flaky_unlink)

    with pytest.raises(RenderError) as exc_info:
        write_outputs(tmp_path, md, json_obj)

    # Not a raw OSError from the failed unlink -- the original RenderError.
    assert isinstance(exc_info.value, RenderError)
    assert isinstance(exc_info.value.__cause__, OSError)
    # Both cleanup targets left after the first `os.replace` failure (the
    # already-renamed md file, and the json tmp file) were attempted, even
    # though the first attempt raised.
    assert len(unlink_attempts) == 2


# --- Required Checks table cell escaping -------------------------------------------


def test_render_markdown_escapes_pipe_and_flattens_newline_in_check_notes() -> None:
    """`CheckResult.notes` is a captured subprocess output tail (`checks.py`'s
    `_tail_notes`, up to 30 lines) and can carry both a literal `|` and embedded
    newlines; either would otherwise break the markdown table row.
    """
    review = replace(
        _approve_review(),
        required_checks=[CheckResult(name='make check', status='fail', notes='line one|with pipe\nline two')],
    )

    md = render_markdown(review)

    rows = [line for line in md.splitlines() if line.startswith('| make check')]
    assert len(rows) == 1
    assert rows[0] == r'| make check | fail | line one\|with pipe line two |'
    assert '\n' not in rows[0]
