"""Acceptance tests for T-09: render `ts-review.md` / `ts-review.json` from a
`Review`, and write both atomically.

Golden files under `tests/fixtures/expected/` are hand-authored against the template
documented in `render.py`'s module docstring, not generated by running the renderer
and pasting its output -- a golden that copies the code proves nothing. `Review`
fixtures are built directly from `compose.Finding` / `compose.Review` /
`checks.CheckResult`, the same way `tests/test_compose.py` does, so this file never
calls the model or `compose()` itself.
"""

from __future__ import annotations

import json
import os
from dataclasses import replace
from pathlib import Path

import pytest

from typesafe_review.ask import AskResult
from typesafe_review.checks import CheckResult
from typesafe_review.compose import UNANSWERED, Finding, Review
from typesafe_review.questions import Severity
from typesafe_review.render import OUTPUT_JSON, OUTPUT_MD, RenderError, render_json, render_markdown, write_outputs
from typesafe_review.verdict import Verdict

FIXTURES = Path(__file__).parent / 'fixtures' / 'expected'


def _finding(
    *,
    severity: Severity,
    file: str | None,
    symbol: str,
    issue: str,
    why: str,
    fix: str,
    question_id: str,
    probability: float | None,
    confidence: float | None = None,
    reason: str | None = None,
) -> Finding:
    return Finding(
        severity=severity,
        file=file,
        symbol_or_area=symbol,
        issue=issue,
        why_it_matters=why,
        concrete_fix=fix,
        blocks_merge=severity in ('blocker', 'important'),
        question_id=question_id,
        probability=probability,
        confidence=confidence,
        reason=reason,
    )


def _counts(findings: list[Finding]) -> dict[str, int]:
    counts = {'blocker': 0, 'important': 0, 'minor': 0, 'nit': 0}
    for f in findings:
        counts[f.severity] += 1
    return counts


