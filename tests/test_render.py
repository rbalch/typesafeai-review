@pytest.mark.parametrize('name', sorted(SCENARIOS))
def test_render_markdown_matches_golden(name: str) -> None:
    review = SCENARIOS[name]()
    actual = render_markdown(review)
    expected = (FIXTURES / f'{name}.md').read_text()
