@pytest.mark.parametrize('name', sorted(SCENARIOS))
def test_written_outputs_match_golden_byte_for_byte(name: str, tmp_path: Path) -> None:
    """The bytes actually written to the worktree -- not just the in-memory dict --
    match the hand-authored golden files exactly, markdown and JSON alike.
    """
    review = SCENARIOS[name]()
    md = render_markdown(review)
    json_obj = render_json(
        review, _engine(), Path('/app/.claude/worktrees/T-09-render'), 'develop', ['note one', 'note two']
    )
    write_outputs(tmp_path, md, json_obj)

    assert (tmp_path / OUTPUT_MD).read_text() == (FIXTURES / f'{name}.md').read_text()
    assert (tmp_path / OUTPUT_JSON).read_text() == (FIXTURES / f'{name}.json').read_text()


